"""Write every recorded case as a Markdown chat, one file per family per model.

  python -m evals.transcripts            -> evals/transcripts/<model>/<family>.md and an index

Reads recordings and baselines only, so it is free and deterministic. Run it after any
`--update-baseline` so the committed transcripts match the committed verdicts.
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path
from typing import Dict, List

from evals.cases import SUITES, Case, load_cases
from evals.run import BASELINES_DIR, baseline_path
from evals.show import markdown, transcript

OUT = Path(__file__).parent / "transcripts"
_FAMILY_BLURB = {
    "reuse": "the agent is named; send it there, spawn nothing",
    "create": "nothing fits; create one",
    "paraphrase": "the follow-up shares no words with the agent; history shows who did the work",
    "trap": "same, with three look-alike names in the roster",
    "drift": "turn 1 creates an agent, turn 2 must come back to it",
    "ambiguous": "two agents fit; ask, or for a question check both",
    "sounds_new": "an agent owns the work but the request reads as new; reuse it",
    "relay": "one question spans two agents; check both and tell the user both answers",
    "long": "the agent's report is behind the conversation summary, 100+ messages back; the follow-up must still reach it",
}


def _slug(model: str) -> str:
    return model.split("/")[-1]


def write_all() -> Dict[str, Dict[str, tuple]]:
    models = sorted({json.loads(p.read_text())["model"] for p in BASELINES_DIR.rglob("*.json")})
    cases = [c for suite in SUITES for c in load_cases(suite)]
    summary: Dict[str, Dict[str, tuple]] = defaultdict(dict)
    for model in models:
        verdicts: Dict[str, str] = {}
        for suite in SUITES:
            path = baseline_path(model, suite)
            if path.exists():
                verdicts.update(json.loads(path.read_text())["verdicts"])
        by_family: Dict[str, List[Case]] = defaultdict(list)
        for case in cases:
            by_family[case.family].append(case)
        for family, family_cases in by_family.items():
            sections, passed = [], 0
            for case in family_cases:
                t = transcript(case, model, 1, verdicts)
                passed += t["passed"]
                sections.append(markdown(t))
            out = OUT / _slug(model) / f"{family}.md"
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(f"# {family} · {model}\n\n{_FAMILY_BLURB.get(family, '')}\n\n"
                           f"{passed} of {len(family_cases)} pass. Generated by `python -m evals.transcripts`.\n\n"
                           + "\n---\n\n".join(sections))
            summary[model][family] = (passed, len(family_cases))
    return summary


def write_index(summary: Dict[str, Dict[str, tuple]]) -> None:
    lines = ["# Eval transcripts", "",
             "Every case as a chat: what the user said, what Poke did, what the tools refused, the verdict.",
             "One file per family per model. Regenerate with `python -m evals.transcripts`.", ""]
    for model, families in summary.items():
        lines += [f"## {model}", "", "| family | pass | file |", "|---|---|---|"]
        for family, (passed, total) in families.items():
            lines.append(f"| {family} | {passed}/{total} | [{family}.md]({_slug(model)}/{family}.md) |")
        lines.append("")
    (OUT / "README.md").write_text("\n".join(lines))


if __name__ == "__main__":
    summary = write_all()
    write_index(summary)
    for model, families in summary.items():
        print(model, {f: f"{p}/{n}" for f, (p, n) in families.items()})
